#!/usr/bin/env python3
"""gen-runtime — the runtime files the editor needs before Fletch, embedded.

Reads this repository's `runtime/` (copied VERBATIM from sagitta's at
`sagitta.pin`; never edited: Fletch stays Fletch, docs/MAP.md §2) and
emits `src/edit/runtime_blob.lu`: one `str` constant per file and one
lookup by relative path, data only. C embeds its runtime only in the
`EMBED_RUNTIME=1` build (`util/runtime_blob.h`); the port always does, as
the last resort after `$YEW_RUNTIME_DIR`, the install prefix and
`./runtime` (`edit/runtime.lu`). `tools/check-runtime` regenerates and
diffs, and diffs the copies against sagitta's.

Usage: gen.py REPO_ROOT OUT
"""
import sys

FILES = ["init.fl", "themes/quiver-dark.fl", "themes/quiver-light.fl"]


def literal(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "{":
            out.append("{{")
        elif ch == "}":
            out.append("}}")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 32 and ch != "\n":
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


def main():
    root, out = sys.argv[1], sys.argv[2]
    with open(out, "w", encoding="utf-8") as f:
        f.write("//! edit.runtime_blob — GENERATED by tools/gen-runtime from this\n")
        f.write("//! repository's `runtime/` (sagitta's, copied verbatim); do not\n")
        f.write("//! edit. `tools/check-runtime` regenerates it and diffs.\n\n")
        names = []
        for i, rel in enumerate(FILES):
            text = open(f"{root}/runtime/{rel}", encoding="utf-8").read()
            name = f"RUNTIME_FILE_{i}"
            names.append((rel, name))
            f.write(f"/// `runtime/{rel}`, byte for byte.\n")
            f.write(f'const {name}: str = """\n{literal(text)}"""\n\n')
        f.write("/// The embedded copy of runtime file `relative`, or (false, \"\").\n")
        f.write("pub fn runtime_embedded(relative: str) -> (bool, str) {\n")
        f.write("    match relative {\n")
        for rel, name in names:
            f.write(f'        "{rel}" => (true, {name}),\n')
        f.write('        _ => (false, ""),\n')
        f.write("    }\n}\n")


main()
