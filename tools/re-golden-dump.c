/*
 * re-golden-dump — sagitta's Sprint 20 golden match table
 * (tests/unit/re_golden.h, 188 rows at 9ace98c2) as the data file the
 * port's test_re_match replays (tests/fixtures/search/re_golden.txt), so
 * the rows stay ONE table: compiled against the oracle tree's own header
 * by tools/check-re-golden and diffed byte for byte.
 *
 * One row a line: pattern and input in hex ("-" when empty), flags,
 * match (0/1), and the expected spans lo hi g1lo g1hi g2lo g2hi (-1:
 * unchecked / must be unset, as re_golden.h's NO).
 */
#include <stdio.h>
#include <string.h>

#include "re_golden.h"

static void hex(const char *s)
{
    size_t i, n = strlen(s);

    if (n == 0U) {
        fputs("-", stdout);
        return;
    }
    for (i = 0U; i < n; i++)
        printf("%02x", (unsigned)(unsigned char)s[i]);
}

int main(void)
{
    size_t i;

    puts("# sagitta 9ace98c2 tests/unit/re_golden.h, generated by tools/re-golden-dump.c (tools/check-re-golden):");
    puts("# pattern-hex input-hex flags match lo hi g1lo g1hi g2lo g2hi; '-' is empty, -1 is NO.");
    for (i = 0U; i < sizeof(rows) / sizeof(rows[0]); i++) {
        hex(rows[i].pat);
        fputc(' ', stdout);
        hex(rows[i].input);
        printf(" %u %d %lld %lld %lld %lld %lld %lld\n", (unsigned)rows[i].flags,
               rows[i].match ? 1 : 0, (long long)rows[i].lo,
               (long long)rows[i].hi, (long long)rows[i].g1lo,
               (long long)rows[i].g1hi, (long long)rows[i].g2lo,
               (long long)rows[i].g2hi);
    }
    return 0;
}
